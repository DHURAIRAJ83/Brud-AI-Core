"""Phase 61 - P1: Admin Assistant Dataset Reasoning & Governance Planner.

Provides provider-routed LLM reasoning for dataset request interpretation,
domain classification, overlap analysis, and preparation recommendations.

CRITICAL INVARIANTS:
- LLM is ADVISORY ONLY.
- LLM CANNOT approve RIGHTS, NOVELTY, ADMIN APPROVAL, or TRAINING AUTHORIZATION.
- All deterministic governance gates remain final authorities.
- Enforces explicit 17-step Brud Dataset Pipeline.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from typing import Any

from backend.services.external_ai_provider_client import ProviderClientProtocol, _result


PIPELINE_STAGES = (
    "SOURCE",
    "RIGHTS",
    "INGESTION",
    "CLEAN_OCR",
    "DOMAIN",
    "EXACT_DEDUP",
    "NORMALIZED_DEDUP",
    "NEAR_DEDUP",
    "GLOBAL_NOVELTY_LEDGER",
    "NATIVE_SYNTHETIC_CLASSIFICATION",
    "TOKEN_ACCOUNTING_ABC",
    "QUALITY",
    "PROVENANCE",
    "HOLDOUT_LEAKAGE",
    "ADMIN_REVIEW",
    "SIGNED_HUMAN_APPROVAL",
    "TRAINING_GATE",
    "TRAINING_LOCKED"
)


@dataclass
class DatasetPreparationPlan:
    """Structured dataset preparation plan generated by Admin Assistant."""
    request_prompt: str
    target_tokens: int
    language: str
    provider_used: str
    advisory_recommendations: list[str]
    pipeline_stages: list[str]
    deterministic_gates_required: list[str]
    rights_approved: bool = False
    novelty_approved: bool = False
    human_approval_signed: bool = False
    training_authorized: bool = False
    status: str = "PENDING_ADMIN_REVIEW"


class AdminAssistantDatasetReasoningEngine:
    """Provider-routed LLM reasoning engine for dataset prep and intent interpretation."""

    def __init__(self, provider_client: ProviderClientProtocol | None = None) -> None:
        self.provider_client = provider_client

    def generate_dataset_prep_plan(
        self,
        request_prompt: str,
        target_tokens: int = 500000,
        language: str = "ta",
    ) -> DatasetPreparationPlan:
        """Formulate a 17-stage dataset preparation plan with advisory LLM suggestions."""
        advisory_notes: list[str] = []
        provider_name = getattr(self.provider_client, "provider_key", "heuristic_fallback")

        if self.provider_client and self.provider_client.is_available():
            prompt = (
                f"Analyze dataset request prompt: '{request_prompt}'. "
                f"Target tokens: {target_tokens}, Language: {language}. "
                "Provide brief advisory suggestions for source discovery, domain tagging, and OCR cleanup."
            )
            try:
                res = self.provider_client.dispatch(prompt=prompt, timeout_seconds=10.0)
                if res.get("status") == "success" and res.get("text"):
                    advisory_notes.append(f"LLM Advisor ({provider_name}): {res['text'][:300]}")
                else:
                    advisory_notes.append(f"LLM Advisor unavailable fallback used: {res.get('error_message')}")
            except Exception as exc:
                advisory_notes.append(f"LLM Dispatch exception: {exc}")
        else:
            advisory_notes.append("Deterministic heuristic reasoning applied (Provider offline/unconfigured).")

        return DatasetPreparationPlan(
            request_prompt=request_prompt,
            target_tokens=target_tokens,
            language=language,
            provider_used=provider_name,
            advisory_recommendations=advisory_notes,
            pipeline_stages=list(PIPELINE_STAGES),
            deterministic_gates_required=[
                "RIGHTS_VERIFIED_GATE",
                "GLOBAL_NOVELTY_LEDGER_GATE",
                "TOKEN_ACCOUNTING_ABC_GATE",
                "SIGNED_HUMAN_APPROVAL_GATE",
                "SIGNED_TRAINING_GATE"
            ],
            rights_approved=False,
            novelty_approved=False,
            human_approval_signed=False,
            training_authorized=False,
            status="PENDING_ADMIN_REVIEW"
        )

    def analyze_domain_gaps_and_recommend_sources(
        self,
        domain_distribution: dict[str, Any],
        target_token_goal: int = 10000000,
        true_new_tokens: int = 0,
    ) -> dict[str, Any]:
        """Analyze corpus domain gaps and produce advisory acquisition recommendations."""
        remaining_gap = max(0, target_token_goal - true_new_tokens)
        underrepresented = domain_distribution.get("underrepresented_domains", [])

        recommendations = []
        for dom in underrepresented:
            recommendations.append(f"Acquire public-domain Tamil books for domain '{dom}' to balance corpus.")

        provider_name = getattr(self.provider_client, "provider_key", "heuristic")

        return {
            "target_token_goal": target_token_goal,
            "verified_true_new_tokens": true_new_tokens,
            "remaining_token_gap": remaining_gap,
            "underrepresented_domains": underrepresented,
            "advisory_source_recommendations": recommendations,
            "provider_used": provider_name,
            "deterministic_governance": "ADVISORY_ONLY"
        }
